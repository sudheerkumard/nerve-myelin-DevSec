def configuration():
    text = open(os.path.join(ROOT, "backend", "app", "config.py"), encoding="utf-8").read()
    rows, seen = [], set()
    for line in text.splitlines():
        m = re.search(r'_(?:get|bool)\("(MYELIN_[A-Z_]+)",\s*([^)]*)\)', line)
        if not m:
            continue
        key, default = m.group(1), m.group(2).strip()
        if key in seen:
            continue
        seen.add(key)
        comment = line.split("#", 1)[1].strip() if "#" in line else ""
        default = default.strip('"\'') if default.startswith(("'", '"')) else default
        if "os.path" in default or "ROOT" in default:
            default = "(installation path)"
        rows.append((f"`{key}`", f"`{default}`" if default else "", DESCRIPTIONS.get(key) or comment))
    for k in sorted(set(re.findall(r'MYELIN_[A-Z_]+', "".join(open(os.path.join(dp, f), encoding="utf-8", errors="ignore").read()
                                                       for base in ("backend/app", "engine/myelin_engine")
                                                       for dp, _, fs in os.walk(os.path.join(ROOT, base)) for f in fs if f.endswith(".py"))))):
        if k not in seen and not k.endswith("_REF") or (k.endswith("_REF") and k not in seen and k in DESCRIPTIONS):
            if k in seen:
                continue
            seen.add(k)
            rows.append((f"`{k}`", "", DESCRIPTIONS.get(k, "")))
    rows = [r for r in rows if r[2] or r[1]]
    return (HEAD + "# Configuration\n\n"
            "Settings are read from the process environment, then the file named by `MYELIN_ENV_FILE`, then `config/backend/myelin.env`. "
            "Values ending in `_REF` are **secret references** (`env://`, `file://`, `vault://`, `azkv://`, `awssm://`), never the secret itself.\n\n"
            "!!! warning \"Demo defaults\"\n    The defaults are safe for local demonstrations only. Enterprise installations set "
            "`MYELIN_MODE=enterprise`, `MYELIN_DEMO_OPEN=false`, a real `MYELIN_CORS` origin and the secret references generated by "
            "`scripts/ops/gen-secrets.sh`.\n\n" + table(sorted(rows), ["Setting", "Default", "Meaning"]))


def main():
    os.makedirs(OUT, exist_ok=True)
    r, total = rules()
    for name, body in (("rules.md", r), ("api.md", api()), ("cli.md", cli()), ("configuration.md", configuration())):
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
            fh.write(body)
        print("wrote docs/reference/" + name)
    print(f"{total} rules")


if __name__ == "__main__":
    main()
