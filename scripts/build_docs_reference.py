"""Generate the reference pages of the documentation site from the code, so they never drift from the product:

    docs/reference/rules.md          every built-in detection rule, by engine
    docs/reference/api.md            every REST endpoint (from the OpenAPI document)
    docs/reference/cli.md            every CLI command and option (from the argument parser)
    docs/reference/configuration.md  every MYELIN_* setting with its default
"""
